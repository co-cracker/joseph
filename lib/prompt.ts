export function buildUserMessage(input: {
  bookTitle: string;
  chapter: string;
  coreConcept: string;
  extraContext?: string;
}): string {
  const lines = [
    `책 제목: ${input.bookTitle}`,
    `챕터: ${input.chapter}`,
    `핵심 개념: ${input.coreConcept}`,
  ];
  if (input.extraContext && input.extraContext.trim().length > 0) {
    lines.push("", "추가 맥락:", input.extraContext.trim());
  }
  lines.push("", "위 정보를 바탕으로 [출력 형식]대로 분석해줘.");
  return lines.join("\n");
}
